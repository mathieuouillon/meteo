#!/usr/bin/env python3
"""Writes the home-screen widget's weather icons as Android vector drawables
(android/app/src/main/res/drawable/wx_<kind>_<light|dark>.xml).

The shapes are the app's line icons from app/ui/icons.slint (32×32 box): keep
the two in sync when changing an icon. Glance can't recolour parts of an
image, so each icon comes in a light and a dark variant (cloud outline and
fill differ).

    python3 scripts/gen-widget-icons.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "android/app/src/main/res/drawable"
LINE = 2.24  # 0.07 of the 32 box, as in icons.slint

SUN, MOON, DROP, FLAKE, BOLT = "#F5A623", "#E9C46A", "#3D8BEA", "#7FB2E5", "#F5B700"
VARIANTS = {
    "light": {"ink": "#5D6672", "cloud": "#FFFFFF"},
    "dark": {"ink": "#C3CAD6", "cloud": "#3A4252"},
}

SUN_DISC = "M 10.5 16 A 5.5 5.5 0 1 0 21.5 16 A 5.5 5.5 0 1 0 10.5 16 Z"
SUN_RAYS = ("M 24.5 16 L 27.5 16 M 22 22 L 24.1 24.1 M 16 24.5 L 16 27.5 M 10 22 L 7.9 24.1 "
            "M 7.5 16 L 4.5 16 M 10 10 L 7.9 7.9 M 16 7.5 L 16 4.5 M 22 10 L 24.1 7.9")
MOON_PATH = "M 19 6.5 A 9.5 9.5 0 1 0 25.5 20 A 7.5 7.5 0 0 1 19 6.5 Z"
SMALL_SUN = ("M 7 12 A 4 4 0 1 0 15 12 A 4 4 0 1 0 7 12 Z M 5 12 L 3 12 M 6.8 7.8 L 5.3 6.3 "
             "M 11 6 L 11 4 M 15.2 7.8 L 16.7 6.3 M 6.8 16.2 L 5.3 17.7")
SMALL_MOON = "M 12.5 4.5 A 6 6 0 1 0 17 13.5 A 4.8 4.8 0 0 1 12.5 4.5 Z"
PARTLY_CLOUD = "M 14 27 A 5 5 0 0 1 13.06 17.09 A 7 7 0 0 1 26.97 17.41 A 5 5 0 0 1 25 27 Z"
CLOUD = "M 11 25 A 5 5 0 0 1 10.06 15.09 A 7 7 0 0 1 23.97 15.41 A 5 5 0 0 1 22 25 Z"
RAISED_CLOUD = "M 11 20 A 5 5 0 0 1 10.06 10.09 A 7 7 0 0 1 23.97 10.41 A 5 5 0 0 1 22 20 Z"
FOG = "M 6 11 L 24 11 M 9 16 L 27 16 M 5 21 L 22 21 M 11 26 L 25 26"
RAIN = "M 11.5 23.5 L 10 28 M 16.5 23.5 L 15 28 M 21.5 23.5 L 20 28"
DRIZZLE = "M 11.5 23.5 L 11 25 M 16.5 23.5 L 16 25 M 21.5 23.5 L 21 25 M 14 27.5 L 13.5 29 M 19 27.5 L 18.5 29"
SNOW = "M 11 24 L 11.01 24 M 16 24 L 16.01 24 M 21 24 L 21.01 24 M 13.5 28 L 13.51 28 M 18.5 28 L 18.51 28"
BOLT_PATH = "M 17 19 L 12.5 25.5 L 16 25.5 L 14.5 30 L 20 23 L 16.5 23 L 18.5 19 Z"


def faint(color):
    """The colour at 30% opacity (#AARRGGBB)."""
    return "#4D" + color[1:]


def icons(v):
    """(kind, [(path, fill, stroke, width)]) for one variant."""
    cloud = lambda d: (d, v["cloud"], v["ink"], LINE)
    raised = cloud(RAISED_CLOUD)
    return {
        "clear_day": [(SUN_DISC, faint(SUN), SUN, LINE), (SUN_RAYS, None, SUN, LINE)],
        "clear_night": [(MOON_PATH, faint(MOON), MOON, LINE)],
        "partly_day": [(SMALL_SUN, faint(SUN), SUN, LINE), cloud(PARTLY_CLOUD)],
        "partly_night": [(SMALL_MOON, faint(MOON), MOON, LINE), cloud(PARTLY_CLOUD)],
        "cloudy": [cloud(CLOUD)],
        "fog": [(FOG, None, v["ink"], LINE)],
        "drizzle": [raised, (DRIZZLE, None, DROP, LINE)],
        "rain": [raised, (RAIN, None, DROP, LINE)],
        "snow": [raised, (SNOW, None, FLAKE, LINE * 1.5)],
        "storm": [raised, (BOLT_PATH, BOLT, BOLT, LINE * 0.6)],
    }


def xml(layers):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by scripts/gen-widget-icons.py from app/ui/icons.slint. -->",
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="32dp" android:height="32dp"',
           '    android:viewportWidth="32" android:viewportHeight="32">']
    for d, fill, stroke, width in layers:
        attrs = [f'android:pathData="{d}"']
        if fill:
            attrs.append(f'android:fillColor="{fill}"')
        if stroke:
            attrs += [f'android:strokeColor="{stroke}"', f'android:strokeWidth="{width:.2f}"',
                      'android:strokeLineCap="round"', 'android:strokeLineJoin="round"']
        out.append("    <path " + "\n        ".join(attrs) + " />")
    out.append("</vector>\n")
    return "\n".join(out)


for variant, colors in VARIANTS.items():
    for kind, layers in icons(colors).items():
        (OUT / f"wx_{kind}_{variant}.xml").write_text(xml(layers))
print(f"wrote {len(VARIANTS) * 10} icons to {OUT}")
